#!/bin/bash
# sdma1 (queue item, 12.11.2026, SDMA-AR agent; gpu02, all 4 cards, every radiance container DOWN; selftest only, <= 12 min) --
# THE COPY ENGINES AS THE ALL-REDUCE'S TRANSPORT (lever SDMA-AR). Image radiance-local:c16-x3sdma1 (branch fn4-x3-sdma-sp
# 7f3fb246 = fn4-x3-sp3 f2b273c1 + libr4d r4d_ar_sdma.hip + r4d_selftest --perfsdma / --sdmaar4).
#  1. r4d_selftest --perfsdma: each card's SDMA engine (0 and 1) copying card -> peer / peer -> card over P2P: one pair,
#     a pair both ways, 1 -> 3, 3 -> 1, every card to its 3 peers (the two-shot's hop), pulled, split over both engines, a
#     local copy; 64 KB .. 42 MB; then a VRAM-bound kernel stream's loss on every card beside the CU exact two-shot
#     (lockstep and xpush = 204's 2508 us) vs beside SDMA copies of the same bytes (engine 0 / 1), at 42 and 10.5 MB.
#  2. r4d_selftest --sdmaar4 (engine 0, then 1; fine-grained scratch): the exact SDMA two-shot, 1000 checked launches a
#     size from a fresh context (inputs regenerated by a kernel each launch, output poisoned by a kernel, every output
#     compared on the card with the fp32 ascending-rank fold), 250 in place, the bytes vs ar_twoshot_4rank_exact on the
#     same input, then timed vs the CU row (lockstep; xpush is gated on by RADIANCE_FN4_AR_XPUSH only in the engine).
# DRYRUN=1 bash 57-p4zyzzzzz-ds-r92zzzzzz-ref12zzzzzzz-fn-sdma1.sh : prints every command, runs and writes nothing.
set -u
DRY=${DRYRUN:-0}
R=$HOME/gpu/ds41/exl3-test/runs; O=$R/fn4; L=$R/ds41-exl3.log
IMG=${XSDMA_IMAGE:-radiance-local:c16-x3sdma1}
C3=GPU-dbba5c851cfef7b3; C83=GPU-4d61f52cafe37588; C86=GPU-5943fea82aeead65; C03=GPU-27d4920317825fce
CARDS=$C3,$C83,$C86,$C03
SIZES=${XSDMA_SIZES:-4096x5120,4096x2560,2048x2560,512x2560,64x2560}
log() { if [ "$DRY" = 1 ]; then echo "[dry, not logged] $(date '+%F %T') $*"; else echo "$(date '+%F %T') $*" | tee -a $L; fi; }
st() {   # st NAME TIMEOUT ENV... -- ARGS : r4d_selftest on the four cards -> $O/sdma1-NAME.txt
  local name=$1 to=$2; shift 2; local envs=()
  while [ "$1" != "--" ]; do envs+=(-e "$1"); shift; done; shift
  local f=$O/sdma1-$name.txt
  if [ "$DRY" = 1 ]; then echo "+ timeout -k 15 $to docker run --rm --init --name fn4-sdma1-$name --network none --device /dev/kfd --device /dev/dri --security-opt seccomp=unconfined -e ROCR_VISIBLE_DEVICES=$CARDS ${envs[*]} --entrypoint /opt/radiance/bin/r4d_selftest $IMG /opt/radiance/share/radiance/kernels/libr4d.so $* > $f"; return 0; fi
  timeout -k 15 $to docker run --rm --init --name fn4-sdma1-$name-$$ --network none --device /dev/kfd --device /dev/dri \
    --security-opt seccomp=unconfined -e ROCR_VISIBLE_DEVICES=$CARDS "${envs[@]}" --entrypoint /opt/radiance/bin/r4d_selftest $IMG \
    /opt/radiance/share/radiance/kernels/libr4d.so "$@" > $f 2>&1
  local rc=$?; docker rm -f fn4-sdma1-$name-$$ > /dev/null 2>&1
  log "RESULT fn4 sdma1 $name: exit $rc ($f)"
  return 0
}
log "RESULT fn4 sdma1: start IMAGE=$IMG ($(docker image inspect -f '{{.Id}}' $IMG 2>/dev/null | cut -c8-19)), cards $CARDS"
if [ "$DRY" != 1 ]; then
  docker ps --format '{{.Names}}' | grep -qiE '^radiance' && { log "RESULT fn4 sdma1: VIRHE a radiance container is running -- the cards are not free"; exit 1; }
  docker image inspect $IMG > /dev/null 2>&1 || { log "RESULT fn4 sdma1: VIRHE image $IMG missing"; exit 1; }
  mkdir -p $O
fi
st perf 300 R4D_SDMA_CONT_KMS=60 -- --perfsdma 65536,262144,1048576,4194304,10485760,20971520,41943040 20
if [ "$DRY" != 1 ]; then
  f=$O/sdma1-perf.txt
  grep -E 'TIMEOUT|no SDMA queue|FAIL|rc -?[0-9]' $f | head -6 | while IFS= read -r l; do log "RESULT fn4 sdma1 note: $(echo "$l" | sed 's/^ *//' | cut -c1-200)"; done
  python3 - $f <<'PY' | while IFS= read -r l; do log "RESULT fn4 sdma1 $l"; done
import json, sys
by = {}
for l in open(sys.argv[1], errors="replace"):
    if l.startswith("SDMA {"):
        d = json.loads(l[5:])
        if "gbs" in d: by.setdefault(d["bytes"], []).append("%s e%d %.1f us %.2f GB/s" % (d["case"], d["engine"], d["us"], d["gbs"]))
    elif l.startswith("SDMACONT {"):
        d = json.loads(l[9:])
        print("contention %.1f MB %s: %d AR %.1f us alone, %.1f us beside; kernel stream %.2f -> %.2f ms = %.1f us lost an AR" % (
            d["mb"], d["arm"], d["nar"], d["ar_alone_us"], d["ar_with_us"], d["k_alone_ms"], d["k_with_ms"], d["loss_us_per_ar"]))
for b in sorted(by):
    if b >= 10485760 or b == 65536:
        print("%.2f MB: %s" % (b / 1e6, "; ".join(by[b])))
PY
fi
for e in 0 1; do
  st ar-e$e 600 R4D_SDMA_ENGINE=$e R4D_SDMA_SCR=1 R4D_SDMA_CHECKS=1000 -- --sdmaar4 $SIZES 100
  if [ "$DRY" != 1 ]; then
    f=$O/sdma1-ar-e$e.txt
    grep -E 'rank [0-9]: rc|error word|no CU|absent' $f | head -6 | while IFS= read -r l; do log "RESULT fn4 sdma1 ar-e$e note: $(echo "$l" | sed 's/^ *//' | cut -c1-200)"; done
    python3 - $f <<'PY' | while IFS= read -r l; do log "RESULT fn4 sdma1 ar-e$e $l"; done
import json, sys
for l in open(sys.argv[1], errors="replace"):
    if l.startswith("SDMAAR {"):
        d = json.loads(l[7:])
        print("%dx%d (%.2f MB): %d launches, bad oop %d / in-place %d / vs CU %d%s; SDMA %.1f us vs CU %.1f us (%+.1f %%); RS half %.1f, AG half %.1f us" % (
            d["rows"], d["width"], d["mb"], d["launches"], d["bad_oop"], d["bad_inplace"], d["bad_vs_cu"], " FAILED" if d["failed"] else "",
            d["us_sdma"], d["us_cu"], 100.0 * (d["us_sdma"] - d["us_cu"]) / d["us_cu"] if d["us_cu"] else 0.0, d["us_rs"], d["us_ag"]))
PY
  fi
done
log "RESULT fn4 sdma1: done ($O/sdma1-*.txt)"
