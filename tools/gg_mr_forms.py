#!/usr/bin/env python3
"""gg_mr_forms.py -- libr4d/r4d_ds41_gg_mr_forms.h, lever D2's measured multi-row forms, from r4d_selftest --perfmr.

    python3 tools/gg_mr_forms.py [--min-gain PCT] [--out FILE] BENCH.txt...

Reads every MRPERF line (r4d_selftest --perfmr: one (type, shape, M) with the stock rule, the pinned stock forms, the
multi-row form's rule "mr-rule" and every pinned multi-row form H<h>R<r>[c<mt>][w<wn>][-w64], each "name us [form]",
"OUTPUT DIFFERS" after a form whose bytes were not the stock rule's) in the files given; a queue log's lines work too.
One key is (ggml type, N, K, M). The table gets a wave32 form for a key only when:

  - its bytes matched the stock rule's in every run that measured the key;
  - it is not the multi-row rule's own pick (H 4, R = N >= 4096 ? 2 : 1, MT and WN the rule's);
  - it beats the multi-row rule by at least --min-gain percent (default 3) in the mean of the runs' form/rule time
    ratios, and is not slower than it in any run. The best such form by that mean is kept.

The head (logits_gemm_ggml, f32 out) is left out: mr_pick reads the table for gemm_nt_ggml only. wave64 forms
(-w64) are bench pins, not a runtime form, and are left out too. Every other key keeps the rule; an entry covers
one M (m_lo == m_hi), as only that M was measured."""
import argparse
import re
import sys

TYPES = {"q8_0": "GG_Q8_0", "q5_K": "GG_Q5_K", "q6_K": "GG_Q6_K"}
HEAD = re.compile(r"MRPERF (\S+) (\S+) (\d+)x(\d+) M=(\d+)(?: \([\d.]+ MiB\))?([^:]*):(.*)$")
FORM = re.compile(r" (\S+) (-?[\d.]+)(?: \[[^\]]*\])?( OUTPUT DIFFERS)?;")
PIN = re.compile(r"^H(\d+)R(\d+)(?:c(\d+))?(?:w(\d+))?$")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="+")
    ap.add_argument("--min-gain", type=float, default=3.0)
    ap.add_argument("--out", default="-")
    a = ap.parse_args()
    runs, names, srcs = {}, {}, []
    for path in a.files:
        n = 0
        for line in open(path, errors="replace"):
            i = line.find("MRPERF ")
            if i < 0:
                continue
            h = HEAD.match(line[i:].rstrip("\n"))
            if not h:
                continue
            ty, shape, N, K, M = h.group(1), h.group(2), int(h.group(3)), int(h.group(4)), int(h.group(5))
            if shape == "head" or ty not in TYPES:
                continue
            forms = {}
            for f in FORM.finditer(h.group(7)):
                us = float(f.group(2))
                if us > 0:
                    forms[f.group(1)] = (us, bool(f.group(3)))
            if "mr-rule" not in forms or forms["mr-rule"][1]:
                continue
            runs.setdefault((ty, N, K, M), []).append(forms)
            names[(ty, N, K, M)] = shape
            n += 1
        srcs.append("%s (%d MRPERF)" % (path, n))
    rows = []
    for key in sorted(runs, key=lambda k: (list(TYPES).index(k[0]), k[1], k[2], k[3])):
        ty, N, K, M = key
        rs = runs[key]
        rule_r = 2 if N >= 4096 else 1
        best = None
        cands = {nm for forms in rs for nm in forms if PIN.match(nm)}
        for nm in cands:
            p = PIN.match(nm)
            H, R, MT, WN = int(p.group(1)), int(p.group(2)), int(p.group(3) or 0), int(p.group(4) or 0)
            if (H, R, MT, WN) == (4, rule_r, 0, 0):
                continue                         # the rule's own pick
            ratios, ok = [], True
            for forms in rs:
                if nm not in forms:
                    continue
                us, differs = forms[nm]
                if differs:
                    ok = False
                    break
                ratios.append(us / forms["mr-rule"][0])
            if not ok or not ratios or max(ratios) > 1.0:
                continue
            mean = sum(ratios) / len(ratios)
            if (1.0 - mean) * 100.0 < a.min_gain:
                continue
            if best is None or mean < best[1]:
                best = ((H, R, MT, WN), mean, len(ratios), nm)
        if best:
            (H, R, MT, WN), mean, n, nm = best
            rule_us = sum(f["mr-rule"][0] for f in rs) / len(rs)
            rows.append((TYPES[ty], N, K, M, M, H, R, MT, WN, "%s %s M=%d: mr rule %.1f us, %s %+.1f %% (%d run%s)" % (
                ty, names[key], M, rule_us, nm, (mean - 1) * 100, n, "" if n == 1 else "s")))
    out = sys.stdout if a.out == "-" else open(a.out, "w")
    out.write("/* r4d_ds41_gg_mr_forms.h -- GENERATED by tools/gg_mr_forms.py; edit the bench data, not this file.\n"
              " *\n"
              " * Lever D2's multi-row form (r4d_ds41_ggml_mr.hip, mr_pick) at a measured wave32 form a (ggml type, N, K, M band)\n"
              " * for gemm_nt_ggml; every other key, and logits_gemm_ggml, keeps the form's rule (H 4, R = N >= 4096 ? 2 : 1). A\n"
              " * form here had the stock rule's bytes at its exact (type, shape, M) in every run, is not the rule's own pick, and\n"
              " * beat it by >= %.1f %% (mean form / rule time) without losing in any run.\n"
              " *\n"
              " * Sources:\n" % a.min_gain)
    for s in srcs:
        out.write(" *   %s\n" % s)
    out.write(" * %d entr%s. */\n" % (len(rows), "y" if len(rows) == 1 else "ies"))
    out.write("#define R4D_GG_MR_FORMS_N %d\n" % len(rows))
    out.write("static const MrTab kMrForms[] = {\n")
    out.write("    /* type      N       K   M lo  M hi   H  R  MT cap  WN */\n")
    for r in rows:
        out.write("    { %-8s %6d, %6d, %4d, %4d, %d, %d, %4d, %d },   /* %s */\n" % (r[0] + ",", r[1], r[2], r[3], r[4], r[5], r[6], r[7], r[8], r[9]))
    if not rows:
        out.write("    { -1, 0, 0, 0, 0, 0, 0, 0, 0 },   /* none: the rule throughout */\n")
    out.write("};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
